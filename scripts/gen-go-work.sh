#!/usr/bin/env bash
# Generate an umbrella go.work over every active Go module so local edits in
# sibling checkouts are used without touching go.mod (ADR-0011). The file is
# gitignored; regenerate after adding or removing submodules.
#   usage: scripts/gen-go-work.sh [--print]
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
export MUXCORE_ROOT="$ROOT"
# shellcheck source=module-sets.sh
source "$ROOT/scripts/module-sets.sh"

goversion=$(go env GOVERSION | sed -E 's/^go([0-9]+\.[0-9]+(\.[0-9]+)?).*/\1/')
{
  echo "// Code generated by scripts/gen-go-work.sh; DO NOT EDIT."
  echo
  echo "go ${goversion}"
  echo
  echo "use ("
  while read -r m; do
    echo "	./$m"
    parent=$(sed -n 's/^module[[:space:]]*//p' "$ROOT/$m/go.mod" | head -1)
    # Nested modules (e.g. core/pkg/contracts, core/sdk/go/*). Only modules
    # whose path lies under the parent's: stub copies of other modules (e.g.
    # media-dlna/stub/core/...) would make module paths ambiguous.
    while read -r nested; do
      [[ "$nested" == "$ROOT/$m/go.mod" ]] && continue
      path=$(sed -n 's/^module[[:space:]]*//p' "$nested" | head -1)
      [[ "$path" == "$parent"/* ]] || continue
      echo "	./${nested#"$ROOT"/}" | sed 's#/go.mod$##'
    done < <(find "$ROOT/$m" -mindepth 2 -name go.mod -not -path '*/node_modules/*' -not -path '*/testdata/*' -not -path '*/cookiecutter/*' | sort)
  done < <(muxcore_active_go_modules)
  echo ")"
} > "$ROOT/go.work.tmp"

if [[ "${1:-}" == "--print" ]]; then cat "$ROOT/go.work.tmp"; rm -f "$ROOT/go.work.tmp"; exit 0; fi
mv "$ROOT/go.work.tmp" "$ROOT/go.work"
echo "gen-go-work: wrote $(grep -c '^	\./' "$ROOT/go.work") modules to go.work"
